/**
 * A repository's tracked files, classified for a codebase map.
 *
 * The PR-side `classify` in `focus.ts` reads a file's patch to decide it is
 * noise; a repository file has no patch, so classification here is by path
 * alone — the same path rules the PR context ranks by (`fileRank`) and the
 * same test rules (`isTestFile`), so a file reads as the same kind on both
 * sides of the app.
 */
import { fileRank } from "@/lib/ai/context";
import { isTestFile } from "@/lib/focus";
import { detectLanguage } from "@/lib/lang";
import type { FileStat } from "@/lib/tauri";

export type RepoFileKind = "source" | "test" | "config" | "doc" | "generated" | "binary";

export interface RepoFile {
  path: string;
  lines: number;
  bytes: number;
  /** Prism language id, `"text"` when unknown. */
  lang: string;
  kind: RepoFileKind;
}

const DOC = /\.(md|mdx|markdown|rst|adoc|txt)$/i;
const DOC_DIR = /(^|\/)docs?\//i;
const DOC_BASENAME = /(^|\/)(readme|changelog|license|contributing|authors|notice)(\.[a-z]+)?$/i;
/** Generated by path, beyond `fileRank`: declaration files and codegen output. */
const GENERATED = [
  /\.d\.ts$/,
  /\.(generated|gen)\.[a-z]+$/i,
  /\.pb\.(go|ts|js)$/,
  /(^|\/)__snapshots__\//,
];

export function classifyRepoFile(stat: FileStat): RepoFile {
  const { path } = stat;
  const rank = fileRank(path);
  const kind: RepoFileKind = stat.binary
    ? "binary"
    : rank === 3 || GENERATED.some((r) => r.test(path))
      ? "generated"
      : isTestFile(path)
        ? "test"
        : DOC.test(path) || DOC_DIR.test(path) || DOC_BASENAME.test(path)
          ? "doc"
          : rank === 2
            ? "config"
            : "source";
  return { path, lines: stat.lines, bytes: stat.bytes, lang: detectLanguage(path), kind };
}
